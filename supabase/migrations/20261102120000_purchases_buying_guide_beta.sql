-- Buying guide (Beta): supermarket receipts -> a usual monthly amount per item -> Usual / Have / Buy.
-- Nothing in the stable app reads these tables; only beta.js does, and only on the Beta profile.

-- One row per receipt (big monthly trip or a small top-up), so every line keeps its store and date.
create table if not exists public.purchases_receipts (
  id bigint generated by default as identity primary key,
  store text not null,
  branch text,
  bought_on date not null,
  bought_time time,
  total numeric(12,2),
  paid numeric(12,2),
  pieces integer,
  source text,                 -- e.g. 'photo' or 'pdf'
  created_at timestamptz not null default now()
);

-- Every printed line, including skipped ones, with how it maps to an app item.
create table if not exists public.purchases_receipt_lines (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.purchases_receipts(id) on delete cascade,
  line_no integer not null,
  barcode text,
  name_ar text not null,
  name_en text,
  qty numeric(12,3) not null,
  qty_unit text,
  unit_price numeric(12,2),
  line_total numeric(12,2),
  discount numeric(12,2) not null default 0,
  item_key text,               -- a purchases_items id, or a purchases_beta_items id ('beta-…'); null when not counted
  app_qty numeric(12,3),       -- amount in the item's unit (e.g. a 3-pack of sponges = 3 pcs)
  app_unit text,
  status text not null check (status in ('OK','NEWITEM','SKIP','ONEOFF','UNKNOWN','CHECK')),
  note text,
  unique (receipt_id, line_no)
);
create index if not exists purchases_receipt_lines_item on public.purchases_receipt_lines (item_key);

-- Items bought regularly that the main list doesn't track yet. They stay in the Beta until moved into purchases_items.
create table if not exists public.purchases_beta_items (
  id text primary key check (id like 'beta-%'),
  name text not null,
  category_id smallint references public.purchases_categories(id) on delete set null,
  unit text not null,
  sort smallint not null default 0
);

-- Hand-set usual monthly amount; when there is no row, the guide uses the receipt average.
create table if not exists public.purchases_usual (
  item_key text primary key,
  qty numeric(12,3) not null check (qty >= 0),
  unit text not null,
  updated_by uuid references public.purchases_profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

-- "Have" for Beta-only items (main items use their latest count from the main list).
create table if not exists public.purchases_beta_stock (
  item_key text primary key references public.purchases_beta_items(id) on delete cascade,
  qty numeric(12,3) not null check (qty >= 0),
  unit text not null,
  counted_by uuid references public.purchases_profiles(id) on delete set null,
  counted_at timestamptz not null default now()
);

alter table public.purchases_receipts enable row level security;
alter table public.purchases_receipt_lines enable row level security;
alter table public.purchases_beta_items enable row level security;
alter table public.purchases_usual enable row level security;
alter table public.purchases_beta_stock enable row level security;

-- Receipts and Beta items are read-only from the app; they are added with SQL after each receipt is checked.
drop policy if exists "receipts read" on public.purchases_receipts;
create policy "receipts read" on public.purchases_receipts for select to anon, authenticated using (true);
drop policy if exists "receipt lines read" on public.purchases_receipt_lines;
create policy "receipt lines read" on public.purchases_receipt_lines for select to anon, authenticated using (true);
drop policy if exists "beta items read" on public.purchases_beta_items;
create policy "beta items read" on public.purchases_beta_items for select to anon, authenticated using (true);
grant select on public.purchases_receipts, public.purchases_receipt_lines, public.purchases_beta_items to anon, authenticated;

-- Usual amounts and Beta counts are edited from the app (upsert needs update as well as insert).
drop policy if exists "usual read" on public.purchases_usual;
create policy "usual read" on public.purchases_usual for select to anon, authenticated using (true);
drop policy if exists "usual write" on public.purchases_usual;
create policy "usual write" on public.purchases_usual for insert to anon, authenticated with check (true);
drop policy if exists "usual update" on public.purchases_usual;
create policy "usual update" on public.purchases_usual for update to anon, authenticated using (true) with check (true);
drop policy if exists "usual delete" on public.purchases_usual;
create policy "usual delete" on public.purchases_usual for delete to anon, authenticated using (true);
grant select, insert, update, delete on public.purchases_usual to anon, authenticated;

drop policy if exists "beta stock read" on public.purchases_beta_stock;
create policy "beta stock read" on public.purchases_beta_stock for select to anon, authenticated using (true);
drop policy if exists "beta stock write" on public.purchases_beta_stock;
create policy "beta stock write" on public.purchases_beta_stock for insert to anon, authenticated with check (true);
drop policy if exists "beta stock update" on public.purchases_beta_stock;
create policy "beta stock update" on public.purchases_beta_stock for update to anon, authenticated using (true) with check (true);
drop policy if exists "beta stock delete" on public.purchases_beta_stock;
create policy "beta stock delete" on public.purchases_beta_stock for delete to anon, authenticated using (true);
grant select, insert, update, delete on public.purchases_beta_stock to anon, authenticated;
